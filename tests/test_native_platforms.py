async def test_a_cover_with_no_routes_reports_and_offers_nothing(
    hass: HomeAssistant, mock_client: AsyncMock, config_entry: MockConfigEntry
) -> None:
    """D62 generalised: a prettier platform is not a reason to lie.

    A hub whose route table cannot move a cover sends the controls with no
    command topic — the reading is still worth having — and the entity must
    then advertise no way to move it.
    """
    message = copy.deepcopy(ENTITY_CHANGE_COVER)
    component = message["cmps"]["cover-cover"]
    for control in component["controls"].values():
        control.pop("command_topic", None)
    component["controls"] = {
        name: control
        for name, control in component["controls"].items()
        if "state_topic" in control
    }
    component.pop("command_topic", None)

    await setup_integration(hass, config_entry)
    await announce(hass, config_entry, message)

    assert hass.states.get(COVER).attributes["supported_features"] == 0


