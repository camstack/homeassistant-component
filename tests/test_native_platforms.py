"""The native platforms: a cover is a cover, and a jammed lock says so.

Every fixture in `fixtures/entity_change_{cover,lock,climate,alarm,vacuum}.json`
was generated by running the hub's OWN `entity-catalog.ts` with the native
platform set negotiated. Nothing in them was typed by hand, so a control
name or a topic this integration gets wrong here gets it wrong against the
hub too — which is the whole reason the wire format is asserted through
recordings rather than through a shape invented to match this code.
"""

