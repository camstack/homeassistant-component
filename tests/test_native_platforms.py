async def test_the_degraded_entities_are_removed_and_the_operator_is_told(
    hass: HomeAssistant, mock_client: AsyncMock, config_entry: MockConfigEntry
) -> None:
    """An entity cannot change domain in place, at any Home Assistant version.

    So the old ones are REMOVED rather than left as orphans — and the
    operator is told, because nothing else would say that
    `sensor.tapparella_salone_cover` has stopped existing until the
    automation using it failed to run.
    """
    await setup_integration(hass, config_entry)
    await announce(hass, config_entry, ENTITY_CHANGE_COVER_LEGACY)
    registry = er.async_get(hass)
    old = registry.async_get_entity_id(
        "sensor", "camstack", "camstack_zigbee:0x0017880109_cover"
    )
    assert old is not None

    await push(hass, config_entry, ENTITY_CHANGE_COVER)

    assert (
        registry.async_get_entity_id(
            "sensor", "camstack", "camstack_zigbee:0x0017880109_cover"
        )
        is None
    )
    assert (
        registry.async_get_entity_id(
            "cover", "camstack", "camstack_zigbee:0x0017880109_cover"
        )
        is not None
    )
    assert _notifications(hass), "the operator was not told the entity id moved"


async def test_an_ordinary_removal_is_not_reported_as_a_migration(
    hass: HomeAssistant, mock_client: AsyncMock, config_entry: MockConfigEntry
) -> None:
    """A device that simply stopped exporting an entity is not a migration.

    The operator is warned about entity ids that MOVED. Warning about every
    removal would train them to ignore the one that matters.
    """
    await setup_integration(hass, config_entry)
    await announce(hass, config_entry, ENTITY_CHANGE_COVER)

    shrunk = copy.deepcopy(ENTITY_CHANGE_COVER)
    del shrunk["cmps"]["sensor-battery"]
    await push(hass, config_entry, shrunk)

    assert not _notifications(hass)
