def _notifications(hass: HomeAssistant) -> dict[str, Any]:
    """Return the persistent notifications, which are not entities."""
    return hass.data.get(pn.DOMAIN, {})


def topic(message: dict[str, Any], entity: str) -> str:
    """Return the state topic the hub builds for one entity of a device."""
    return f"camstack/{message['device_id']}/{entity}"


def state_update(topic_name: str, value: str) -> dict[str, Any]:
    """Return one state update as the hub sends it — the value is a STRING."""
    return {"type": "state_update", "topic": topic_name, "value": value}


async def announce(
    hass: HomeAssistant, entry: MockConfigEntry, message: dict[str, Any]
) -> None:
    """Deliver one device and bring the link up."""
    await push(hass, entry, message)
    await push(hass, entry, HEARTBEAT)


